def check_rate():
    """利率敏感性表自检:
    ①±对称、200bp=2×100bp(公司表自身线性);
    ②RLDC 与自留率派生可复算;
    ③+100bp 的储备收入增量 ≈ 储备资产 ×1%(跨表核 USDC运营.csv 储备构成两行)。"""
    d = {lb: dict(zip(RATE_COLS, vals)) for lb, vals in RATE_ROWS}
    base = dict(RATE_BASE)
    for tag in ("2025-12基准·当期", "2024-12基准·上年比较"):
        pre = tag.split("基准")[0] + "基准"
        ri = next(v for k, v in d.items() if k.startswith(f"【{tag}】储备收入") or
                  (k.startswith(f"【{pre}") and "储备收入" in k))
        dc = next(v for k, v in d.items() if k.startswith(f"【{pre}") and "分销与交易成本" in k)
        rl = next(v for k, v in d.items() if k.startswith(f"【{pre}") and "RLDC变动" in k)
        kp = next(v for k, v in d.items() if k.startswith(f"【{pre}") and "自留比例" in k)
        for a, b in (("+200bp", "+100bp"), ("-200bp", "-100bp")):
            chk(eq(ri[a], 2 * ri[b], tol=1), f"利率表 {pre} {a} 储备收入 ≠ 2×{b}")
            chk(eq(dc[a], 2 * dc[b], tol=1), f"利率表 {pre} {a} 分销成本 ≠ 2×{b}")
        for p, m in (("+200bp", "-200bp"), ("+100bp", "-100bp")):
            chk(eq(ri[p], -ri[m], tol=0), f"利率表 {pre} {p}/{m} 储备收入不对称")
            chk(eq(dc[p], -dc[m], tol=0), f"利率表 {pre} {p}/{m} 分销成本不对称")
        for c in RATE_COLS:
            chk(eq(ri[c] - dc[c], rl[c], tol=1), f"利率表 {pre} {c}: RLDC 派生 ≠ 储备收入−分销成本")
            chk(eq(round(rl[c] / ri[c], 4), kp[c], tol=0.0002),
                f"利率表 {pre} {c}: 自留率 {kp[c]} ≠ 复算 {round(rl[c]/ri[c], 4)}")
    # 跨表:储备资产合计须等于 USDC运营.csv 的「银行现金 + Circle Reserve Fund」
    cash = dict(zip(USDC_YEARS, V(USDC_ROWS, "储备构成-银行现金")))
    crf = dict(zip(USDC_YEARS, V(USDC_ROWS, "储备构成-Circle Reserve Fund")))
    for y, lb in ((2025, "2025-12-31 储备资产合计"), (2024, "2024-12-31 储备资产合计")):
        chk(eq(base[next(k for k in base if k.startswith(lb))], cash[y] + crf[y], tol=1),
            f"利率表 {y} 储备资产合计 ≠ USDC运营.csv 现金+CRF ({cash[y] + crf[y]})")
    # +100bp 储备收入增量应贴近「储备资产 ×1%」(公司模型=全额传导)
    ri25 = d["【2025-12基准·当期】储备收入变动(百万美元)"]["+100bp"]
    chk(eq(ri25, round(base["2025-12-31 储备资产合计(百万美元·=银行现金+CRF)"] * 0.01), tol=5),
        f"利率表 2025: +100bp 储备收入 {ri25} 偏离 储备资产×1% 超容差")
    # 打平所需流通量变动: 1 − y0/(y0+Δ)
    y0 = base["2025-12 平均收益率(公司原文基准)"]
    be = d["【2025-12基准】储备收入打平所需流通量变动(派生·正=可跌/负=须涨)"]
    for c, dbp in (("+200bp", 0.02), ("+100bp", 0.01), ("-100bp", -0.01), ("-200bp", -0.02)):
        want = round(1 - y0 / (y0 + dbp), 4)
        chk(eq(want, be[c], tol=0.0002),
            f"利率表 打平量变动 {c}: 表内 {be[c]} ≠ 复算 {want}")


def check_arc():
    """ARC 代币表自检: 量×价=毛额、FDV=初始供应×价、占比可复算、关联方金额自洽、
    且预售毛额须与 资产负债表/中期表 的其他流动负债跳升口径一致(编年 242.2)。"""
    a = dict(ARC_ROWS)
    px = a["预售价格(美元/枚)"]
    chk(eq(round(a["预售合计(百万枚·两轮)"] * px, 1), a["预售毛额(百万美元)"], tol=0.1),
        f"ARC: 预售量×价 {round(a['预售合计(百万枚·两轮)'] * px, 1)} ≠ 毛额 {a['预售毛额(百万美元)']}")
    chk(eq(a["预期初始总供应量(百万枚)"] * px, a["隐含完全稀释估值FDV(百万美元·=初始供应×预售价)"], tol=1),
        "ARC: FDV ≠ 初始供应×预售价")
    chk(eq(round(a["预售合计(百万枚·两轮)"] / a["预期初始总供应量(百万枚)"], 5),
           a["预售占初始供应"], tol=1e-5), "ARC: 预售占比复算不符")
    chk(eq(round(a["其中关联方认购-IDG Capital关联实体(百万枚·2026-05-08)"] * px, 1),
           a["其中关联方认购-IDG Capital关联实体(百万美元)"], tol=0.1),
        "ARC: 关联方 量×价 ≠ 金额")
    chk(eq(round(a["其中关联方认购-IDG Capital关联实体(百万美元)"] / a["预售毛额(百万美元)"], 4),
           a["关联方认购占预售毛额比例"], tol=0.0002), "ARC: 关联方占比复算不符")
    # 预售款全额挂在其他流动负债 → 2026-06-30 其他流动负债跳升应覆盖该金额
    ocl = 256021  # 千美元·10-Q 2026-06-30 其他流动负债(README 口径决策 11)
    chk(a["预售毛额(百万美元)"] * 1000 <= ocl,
        f"ARC: 预售毛额 {a['预售毛额(百万美元)']}百万 超出其他流动负债 {ocl}千美元, 口径矛盾")


def check_scen():
    """情景组合表自检:
    ①量冲击系数须取自 中期-2026H1.csv 的平台占比源行(不得自造);
    ②「加息100bp×奖励保住」相对基准的增量须与公司自测 +100bp 表一致(容差5);
    ③交互效应放大倍数 = 收益率之比(证明"禁奖励的伤害随利率线性放大"是恒等式不是估计);
    ④基准情形储备收入须贴近 储备资产×基准收益率。"""
    d = {lb: dict(zip(SCEN_COLS, vals)) for lb, vals in SCEN_ROWS}
    it = dict(SCEN_INTERACT)
    h1 = dict(zip(H1_COLS, V(H1_ROWS, "平台上USDC日加权占比")))
    chk(eq(round(1 - SCEN_VOL[1], 3), round(h1["2026Q2"], 3), tol=0.001),
        f"情景表: 量冲击 {round(1 - SCEN_VOL[1], 3)} ≠ 中期表 2026Q2 平台占比 {h1['2026Q2']}")
    base = d["储备收入(百万美元·=75,333×收益率×量系数)"]["基准×奖励保住"]
    up = d["储备收入(百万美元·=75,333×收益率×量系数)"]["加息100bp×奖励保住"]
    rate100 = dict(zip(RATE_COLS, V(RATE_ROWS, "【2025-12基准·当期】储备收入变动")))["+100bp"]
    chk(eq(up - base, rate100, tol=5),
        f"情景表: 加息100bp 增量 {up - base} 与公司自测表 {rate100} 不一致")
    lo = it["降息100bp档:禁奖励的边际损失(百万美元)"]
    hi = it["加息100bp档:禁奖励的边际损失(百万美元)"]
    chk(eq(round(hi / lo, 3), round(it["加息档损失÷降息档损失(倍·=4.64%÷2.64%)"], 3), tol=0.002),
        f"情景表: 交互放大倍数 {round(hi/lo, 3)} ≠ 收益率比 {it['加息档损失÷降息档损失(倍·=4.64%÷2.64%)']}")
    chk(eq(base, round(75333 * 0.0364), tol=1), f"情景表: 基准储备收入 {base} ≠ 储备资产×3.64%")


def check_holders():
    """机构股东表自检: 仅 2026-06-30 期申报明示了分母, 该格百分比必须可复算。"""
    d = {lb: dict(zip(HOLD_COLS, vals)) for lb, vals in HOLD_ROWS}
    den = d["A类在外股数(股·仅2026-06-30期申报明示分母=10-Q封面2026-07-30数)"]["2026-06-30"]
    sh = d["Chuang Xi Capital(IDG系·含Wide Palace)持股(股)"]["2026-06-30"]
    pc = d["Chuang Xi Capital 占A类%(申报自报)"]["2026-06-30"]
    chk(eq(round(sh / den * 100, 1), pc, tol=0.05),
        f"机构股东 2026-06-30: Chuang Xi {pc}% ≠ 复算 {round(sh/den*100, 1)}%")
    # 分母须与 中期-2026H1.csv 的 A 类股数行同源(千股 → 股)
    a_cls = dict(zip(H1_COLS, V(H1_ROWS, "A类普通股-期末")))
    chk(eq(den, round(a_cls["2026H1"] * 1000), tol=1),
        f"机构股东分母 {den} ≠ 中期表A类股数 {round(a_cls['2026H1'] * 1000)}")


def check_insider():
    """内部人表自检: ①均价=金额÷股数 ②合计列=各季之和。"""
    d = {lb: dict(zip(INSIDER_COLS, vals)) for lb, vals in INSIDER_ROWS}
    qs = INSIDER_COLS[:-1]
    for c in INSIDER_COLS:
        sh, val, px = (d["公开市场卖出股数(股·S码)"][c], d["公开市场卖出金额(美元·S码)"][c],
                       d["加权均价(美元/股)"][c])
        chk(eq(round(val / sh, 2), px, tol=0.01), f"内部人 {c}: 均价 {px} ≠ 复算 {round(val/sh, 2)}")
    for lb in ("公开市场卖出股数(股·S码)", "公开市场卖出金额(美元·S码)",
               "税款代扣缴回股数(股·F码·非市场卖出)", "期权/RSU行权取得股数(股·M码)",
               "授予股数(股·A码)", "C码取得A类股(股·含B类转A类)"):
        s = sum(d[lb][c] for c in qs)
        chk(eq(s, d[lb]["合计"], tol=0), f"内部人 {lb}: 各季之和 {s} ≠ 合计 {d[lb]['合计']}")


