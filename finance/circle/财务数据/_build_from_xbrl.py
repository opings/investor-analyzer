def V(rows, label_prefix):
    for lb, vals in rows:
        if lb.startswith(label_prefix):
            return vals
    raise KeyError(label_prefix)


def chk(cond, msg):
    if not cond:
        FAIL.append(msg)


def eq(a, b, tol=0):
    if a is None or b is None:
        return True  # 缺项不勾
    return abs(a - b) <= tol


