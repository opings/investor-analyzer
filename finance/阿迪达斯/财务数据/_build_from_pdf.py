def tol(year):
    """容差：2006 起年报按百万取整（公司自陈 rounding differences may arise）→ 放宽到 2。"""
    return 2.0 if UNIT[year] == "million_eur" else 0.2


def check(errors, year, name, lhs, rhs):
    if lhs is None or rhs is None:
        return
    if abs(lhs - rhs) > tol(year):
        errors.append(f"  ❌ {year} {name}: {lhs} vs {rhs}  差 {round(lhs - rhs, 2)}")


def validate():
    errors, warns = [], []

    # ── C0 必填项：某年有该表任何数据，这些锚科目就必须有值 ───────────
    #    （耐克建库教训：勾稽以锚科目存在为前提时，锚丢了会静默全过）
    for y, d in IS.items():
        for k in ("营业收入", "营业成本", "毛利", "税前利润", "所得税", "归母净利润"):
            if d.get(k) is None:
                errors.append(f"  ❌ C0 利润表 {y} 缺必填项「{k}」")
    for y, d in BS.items():
        for k in ("资产总计", "流动资产合计", "流动负债合计", "归母股东权益", "货币资金", "存货"):
            if d.get(k) is None:
                errors.append(f"  ❌ C0 资产负债表 {y} 缺必填项「{k}」")
    for y, d in CF.items():
        for k in ("经营活动现金流净额", "投资活动现金流净额", "融资活动现金流净额",
                  "期初现金", "期末现金", "购置物业厂房及设备"):
            if d.get(k) is None:
                errors.append(f"  ❌ C0 现金流量表 {y} 缺必填项「{k}」")

    # ── 利润表 ────────────────────────────────────────────────
    for y, d in IS.items():
        g = d.get
        check(errors, y, "营收−成本=毛利", g("营业收入") - g("营业成本"), g("毛利"))
        # 经营利润链（两代版式）
        if g("销售管理及一般费用") is not None:           # 1994–2005 版式
            op = g("毛利") - g("销售管理及一般费用") - (g("折旧摊销") or 0)
            if y >= 2005:                                  # 2005 起特许权收入已上提到经营利润之上
                op += g("特许权及佣金收入") or 0
            check(errors, y, "毛利−SG&A−折旧=经营利润", op, g("经营利润"))
        elif g("其他经营损益净额") is not None:            # 2006–2007 版式（收支合并列示）
            check(errors, y, "毛利+特许权−其他经营损益=经营利润",
                  g("毛利") + (g("特许权及佣金收入") or 0) - g("其他经营损益净额"), g("经营利润"))
        else:                                              # 2008 起版式
            op = (g("毛利") + (g("特许权及佣金收入") or 0) + (g("其他经营收益") or 0)
                  - (g("其他经营费用") or 0) - (g("商誉减值损失") or 0))
            check(errors, y, "毛利+特许权+其他收益−其他费用=经营利润", op, g("经营利润"))
        # 税前利润链
        if g("财务费用净额") is not None:                  # 1994–2004
            ibt = (g("经营利润") - (g("商誉摊销") or 0) + (g("特许权及佣金收入") or 0)
                   - g("财务费用净额") + (g("非经常性收益") or 0))
        else:                                              # 2005+
            ibt = g("经营利润") + (g("财务收益") or 0) - (g("财务费用") or 0)
        check(errors, y, "经营利润→税前利润", ibt, g("税前利润"))
        # 税后链
        ni_c = g("持续经营净利润") if g("持续经营净利润") is not None else g("合并净利润")
        check(errors, y, "税前−所得税=(持续经营)净利润", g("税前利润") - g("所得税"), ni_c)
        if g("终止经营损益") is not None and g("持续经营净利润") is not None:
            check(errors, y, "持续+终止=合并净利润",
                  g("持续经营净利润") + g("终止经营损益"), g("合并净利润"))
        # 合并净利润 − 少数股东损益 = 归母（两代版式同向：老版「Minority interests」印正数亦为减项）
        if g("少数股东损益") is not None and g("合并净利润") is not None:
            base = g("特别项目前净利润") if g("特别项目前净利润") is not None else g("归母净利润")
            check(errors, y, "合并净利润−少数股东=归母", g("合并净利润") - g("少数股东损益"), base)

    # ── 资产负债表 ─────────────────────────────────────────────
    for y, d in BS.items():
        g = d.get
        check(errors, y, "资产总计=负债及权益总计", g("资产总计"), g("负债及权益总计"))
        if g("非流动资产合计") is not None:
            check(errors, y, "流动+非流动=资产总计",
                  g("流动资产合计") + g("非流动资产合计"), g("资产总计"))
        eq = g("权益合计") if g("权益合计") is not None else (g("归母股东权益") or 0) + (g("少数股东权益") or 0)
        if g("非流动负债合计") is not None:
            check(errors, y, "流动负债+非流动负债+权益=总计",
                  g("流动负债合计") + g("非流动负债合计") + eq, g("负债及权益总计"))
        if g("股本") is not None:
            check(errors, y, "股本+储备+留存=归母权益",
                  g("股本") + g("储备") + g("留存收益"), g("归母股东权益"))

    # ── 现金流量表 ─────────────────────────────────────────────
    for y, d in CF.items():
        g = d.get
        # 2023 年报把 IAS 29 恶性通胀影响单列在三大活动之外（2024 起改并入经营活动内）
        check(errors, y, "经营+投资+融资+恶性通胀+汇率=现金净变动",
              g("经营活动现金流净额") + g("投资活动现金流净额") + g("融资活动现金流净额")
              + (g("恶性通胀影响") or 0) + (g("汇率影响") or 0), g("现金净变动"))
        check(errors, y, "期初+净变动=期末", g("期初现金") + g("现金净变动"), g("期末现金"))
        if g("经营活动现金流净额_持续经营") is not None:
            check(errors, y, "持续+终止=经营现金流",
                  g("经营活动现金流净额_持续经营") + (g("经营活动现金流净额_终止经营") or 0),
                  g("经营活动现金流净额"))

    # ── 跨表勾稽 ───────────────────────────────────────────────
    for y in sorted(set(IS) & set(CF)):
        check(errors, y, "利润表税前利润=现金流量表税前利润", IS[y]["税前利润"], CF[y]["税前利润"])
    for y in sorted(set(BS) & set(CF)):
        check(errors, y, "资产负债表货币资金=现金流量表期末现金",
              BS[y]["货币资金"], CF[y]["期末现金"])
    # 现金流量表期末现金 = 次年期初现金（as-reported 口径断点会在此暴露）
    ys = sorted(CF)
    for a, b in zip(ys, ys[1:]):
        if b - a != 1:
            continue
        # 🔴 必须折算成同一单位再比：1999 印 DM 千、2000 印 € 千、2006 起印 € 百万，
        #    直接比印刷值会造出三条假断点（本库自查实证）。
        ea, sb = to_eur_mn(a, CF[a]["期末现金"]), to_eur_mn(b, CF[b]["期初现金"])
        if abs(ea - sb) > max(tol(a), tol(b)):
            warns.append(f"  ⚠️ {a}期末现金 €{ea}mn ≠ {b}期初现金 €{sb}mn"
                         f"（as-reported 跨年口径断点，见 重述与口径变更.csv）")

    # ── DM→EUR 换算独立验证：1999 两个口径必须一致 ─────────────────
    dm99 = to_eur_mn(1999, IS[1999]["营业收入"])
    eur99_company = 5353.949  # 2000 年报把 1999 折成欧元后印的值（€ 000 → 百万）
    if abs(dm99 - eur99_company) > 0.15:
        errors.append(f"  ❌ DM→EUR 换算校验失败：1999 营收换算 {dm99} vs 公司自折 {eur99_company}")

    return errors, warns


def write_csv(path, rows, data, title):
    years = sorted(data)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow([f"# {title}｜单位：€ 百万（1994-1999 由 DM 按 1 EUR=1.95583 DM 折算）"
                    f"｜空=该期财报无此科目(非 0)｜真源：report/阿迪达斯/*.pdf"])
        w.writerow(["科目"] + [str(y) for y in years])
        for r in rows:
            if not any(data[y].get(r) is not None for y in years):
                continue
            line = [r]
            for y in years:
                v = to_eur_mn(y, data[y].get(r), r)
                line.append("" if v is None else v)
            w.writerow(line)
        w.writerow(["数据来源"] + [data[y]["src"] for y in years])


