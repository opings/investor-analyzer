# ── 每年的「印刷单位 → € 百万」换算因子 ───────────────────────────────
#    thousand_dm : 年报印 DM 千  → ÷1000 ÷1.95583
#    thousand_eur: 年报印 €  千  → ÷1000
#    million_eur : 年报印 €  百万 → 原样
UNIT = {y: "thousand_dm" for y in range(1994, 2000)}
UNIT.update({y: "thousand_eur" for y in range(2000, 2006)})
UNIT.update({y: "million_eur" for y in range(2006, 2026)})


# 每股数据是「元/股」不是「千元」——只做币种折算，绝不做千→百万
PER_SHARE = {"基本每股收益", "稀释每股收益"}


def to_eur_mn(year, v, row=None):
    """把年报印刷值折成 € 百万（每股行折成 €/股）。None 透传（= 该年无此科目，不是 0）。"""
    if v is None:
        return None
    u = UNIT[year]
    if row in PER_SHARE:
        return round(v / DM_PER_EUR, 2) if u == "thousand_dm" else v
    if u == "thousand_dm":
        return round(v / 1000.0 / DM_PER_EUR, 1)
    if u == "thousand_eur":
        return round(v / 1000.0, 1)
    return v


