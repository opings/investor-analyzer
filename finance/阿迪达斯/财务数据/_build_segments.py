def conv(year, v):
    """1992-1996 年报以 DM 百万列报 → 折欧元百万。"""
    return round(v / DM_PER_EUR, 1) if year in DM_YEARS else v


def main():
    years = sorted({y for _, _, _, d in DATA for y in d})
    path = os.path.join(HERE, "分部营收.csv")
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["# 阿迪达斯 分部营收｜单位：€ 百万（1992-1996 由 DM 按 1 EUR=1.95583 DM 折算）"
                    "｜空 = 该年该口径未披露(非 0)"])
        w.writerow(["# 🔴 分部口径六代不可跨代拼接（公司每次重划且不给回溯序列）；"
                    "2004 起「其他业务」含 Salomon/TaylorMade/Reebok 等已剥离业务，2021 起 Reebok 已剔出"])
        w.writerow(["# 取数规则：当年年报当年列；唯一例外=分品牌 2013-2020 取自 2020 年报十年概览（见「来源」列）"])
        w.writerow(["维度", "口径代", "分部"] + [str(y) for y in years] + ["来源"])
        for dim, gen, seg, d in DATA:
            w.writerow([dim, gen, seg] + [conv(y, d[y]) if y in d else "" for y in years]
                       + [SRC.get(gen, "")])

    # ── 勾稽：各维度各年分部合计 vs 利润表营收 ───────────────────
    print("分部合计 vs 利润表营收（差额 = 总部/未分摊，年报自陈可有）：")
    bad = 0
    for dim in ("地区", "产品"):
        for y in years:
            tot = sum(d[y] for dd, _, _, d in DATA if dd == dim and y in d)
            if tot == 0 or y not in REV:
                continue
            rev = REV[y]
            gap = (tot - rev) / rev
            flag = "✅" if abs(gap) < 0.03 else "⚠️"
            if abs(gap) >= 0.03:
                bad += 1
            print(f"  {flag} {dim} {y}: 分部合计 {tot:,} vs 营收 {rev:,}  差 {gap:+.1%}")
    print(f"\n已写出 分部营收.csv（{len(DATA)} 行 × {len(years)} 年）；超 3% 差异 {bad} 处")


if __name__ == "__main__":
    main()
