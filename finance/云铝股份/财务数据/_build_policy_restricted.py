#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""云铝股份 政策性收益与受限资产构建器 → 政策性收益与受限资产.csv

为什么建（2026-09-14 全库附注审计）：本库此前只有三表+分部，**零专题表**。
对一家电解铝（强周期·高耗能·政策敏感）公司，下面两块是实质内容而非样板：
  ① **政策性收益** —— 审计发现「政府补助」在年报里出现在**四个不同位置、含义各不相同**，
     混用会算错。且真正的大头不是直接补助，而是**增值税进项加计抵减**。
  ② **受限资产** —— 抵押融资规模与受限现金性质。

⚠️ 审计里「衍生/套期 19 次」经查**大部分是非经常性损益的定义条文**（「除…有效套期保值业务外」），
   年报明示「净敞口套期收益 **不适用**」「衍生金融负债 **不适用**」→ 本表不设套期段。

数据来源（全部一手·云铝股份 2025 年年度报告）：
  · 附注 67「其他收益」 · 非经常性损益明细表 · 「所有权或使用权受到限制的资产」
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "政策性收益与受限资产.csv")

# 附注67 其他收益（元）
OTHER_INCOME = {
    "与收益相关的政府补助": {"2024": 9748972.48, "2025": 10503795.50},
    "增值税进项加计抵减": {"2024": 335150284.88, "2025": 186262400.54},
}
OI_TOTAL = {"2024": 344899257.36, "2025": 196766196.04}

# 非经常性损益表里的「计入当期损益的政府补助」（已剔除持续性补助·元）
NR_GRANT = {"2023": 30479656.40, "2024": 26477144.92, "2025": 20324442.07}

# 受限资产（元）
RESTRICTED = {
    "货币资金": {"2024": 103014638.17, "2025": 105465690.18},
    "固定资产": {"2024": 3692578.26, "2025": 3551009.75},
    "无形资产": {"2024": 32433216.00, "2025": 31034110.39},
}
RES_TOTAL = {"2024": 139140432.43, "2025": 140050810.32}
PLEDGE_LOAN = {"2024": 188000000.00, "2025": 188000000.00}

# 归母净利（元·取自 利润表.csv）
NI = {"2023": 3955771178.74, "2024": 4411670800.53, "2025": 6054686552.59}


def main():
    errs, nchk = [], 0
    for y in ("2024", "2025"):
        nchk += 1
        s = sum(v[y] for v in OTHER_INCOME.values())
        if abs(s - OI_TOTAL[y]) > 1:
            errs.append(f"[{y}] 其他收益分项之和 {s:,.2f} ≠ 合計 {OI_TOTAL[y]:,.2f}")
        nchk += 1
        s2 = sum(v[y] for v in RESTRICTED.values())
        if abs(s2 - RES_TOTAL[y]) > 1:
            errs.append(f"[{y}] 受限资产分项之和 {s2:,.2f} ≠ 合計 {RES_TOTAL[y]:,.2f}")
        nchk += 1
        if RES_TOTAL[y] > NI[y]:
            errs.append(f"[{y}] 受限资产超过归母净利，需复核口径")
    if errs:
        print(f"❌ 校验不通过 {len(errs)}：")
        for e in errs:
            print("   ✗", e)
        return 1

    def pct(a, b):
        return f"{a / b * 100:.2f}%"

    rows = [
        ["单位:元(人民币)，与年报原始口径一致;占比为派生"],
        ["来源:2025 年年度报告 —— 附注67「其他收益」/ 非经常性损益明细表 /「所有权或使用权受到限制的资产」"],
        ["🔴 本表 2026-09-14 补建 —— 此前本库只有三表+分部、零专题表"],
        [],
        ["【A · 「政府补助」的四个口径 —— 🚨 含义不同，不可混用、不可相加】"],
        ["口径", "在年报哪里", "含义", "2024", "2025"],
        ["① 与收益相关的政府补助", "附注67 其他收益", "计入其他收益、与日常经营相关的补助",
         f"{OTHER_INCOME['与收益相关的政府补助']['2024']:,.2f}",
         f"{OTHER_INCOME['与收益相关的政府补助']['2025']:,.2f}"],
        ["② 计入当期损益的政府补助", "非经常性损益明细表", "**已剔除**「对损益产生持续影响」的那部分，故小于①+③",
         f"{NR_GRANT['2024']:,.2f}", f"{NR_GRANT['2025']:,.2f}"],
        ["③ 递延收益中的政府补助", "递延收益附注", "**与资产相关**、分期摊销，非当期损益", "见年报递延收益附注 ⏳", "⏳"],
        ["④ 收到的政府补助现金", "现金流量表补充资料", "**收付实现制**，与①②③的权责发生制口径都不同", "⏳", "⏳"],
        ["⚠️ 本表只把①与②做成序列；③④标 ⏳ 留待专门一遍。**任何「云铝拿了多少补贴」的说法都必须先说明是哪个口径**"],
        [],
        ["【B · 其他收益构成 —— 🔴 大头不是补助，是增值税加计抵减】"],
        ["项目", "2024", "2025", "同比", "2025 占比"],
    ]
    for k, v in OTHER_INCOME.items():
        rows.append([k, f"{v['2024']:,.2f}", f"{v['2025']:,.2f}",
                     f"{v['2025'] / v['2024'] * 100 - 100:+.1f}%", pct(v["2025"], OI_TOTAL["2025"])])
    rows.append(["合计", f"{OI_TOTAL['2024']:,.2f}", f"{OI_TOTAL['2025']:,.2f}",
                 f"{OI_TOTAL['2025'] / OI_TOTAL['2024'] * 100 - 100:+.1f}%", "100.00%"])
    rows.append(["其他收益 ÷ 归母净利", pct(OI_TOTAL["2024"], NI["2024"]), pct(OI_TOTAL["2025"], NI["2025"]), "", ""])
    rows.append([
        "🔑 读法:**「政策给的钱」里约 95% 是增值税进项加计抵减，不是财政补助**；"
        f"该项 2024→2025 由 {OTHER_INCOME['增值税进项加计抵减']['2024']/1e8:.2f} 亿降至 "
        f"{OTHER_INCOME['增值税进项加计抵减']['2025']/1e8:.2f} 亿（−44.4%），"
        "使其他收益整体腰斩。加计抵减是**税收优惠政策**、有适用期限与行业目录，"
        "退坡风险与财政补助不同源，须单独跟踪"])

    rows += [
        [],
        ["【C · 所有权或使用权受限的资产】"],
        ["项目", "2024 账面价值", "2025 账面价值", "受限性质"],
    ]
    for k, v in RESTRICTED.items():
        note = {"货币资金": "土地复垦及环境治理恢复金（**非抵押**，是环保义务保证金）",
                "固定资产": "抵押（与无形资产合并担保长期借款）",
                "无形资产": "土地使用权抵押"}[k]
        rows.append([k, f"{v['2024']:,.2f}", f"{v['2025']:,.2f}", note])
    rows.append(["合计", f"{RES_TOTAL['2024']:,.2f}", f"{RES_TOTAL['2025']:,.2f}", ""])
    rows.append(["对应长期借款本金", f"{PLEDGE_LOAN['2024']:,.2f}", f"{PLEDGE_LOAN['2025']:,.2f}",
                 "以土地使用权（原值 61,840,132.01）+ 固定资产（原值 5,597,843.82）抵押取得"])
    rows.append(["受限资产 ÷ 归母净利", pct(RES_TOTAL["2024"], NI["2024"]), pct(RES_TOTAL["2025"], NI["2025"]), ""])
    rows.append(["🔑 读法:受限规模很小（不到归母净利的 4%），**不构成资金受限风险**；"
                 "且受限现金主要是**环保恢复金**而非质押——这是电解铝这类高耗能行业的常规义务，不是财务紧张信号"])

    with open(OUT, "w", encoding="utf-8", newline="") as f:
        csv.writer(f).writerows(rows)

    print(f"── 政策性收益与受限资产校验：{nchk} 条，不通过 0")
    print("✅ 政策性收益与受限资产.csv 已写出")
    print(f"   🔴 增值税进项加计抵减 {OTHER_INCOME['增值税进项加计抵减']['2024']/1e8:.2f}亿 → "
          f"{OTHER_INCOME['增值税进项加计抵减']['2025']/1e8:.2f}亿（−44.4%），占 2025 其他收益 "
          f"{pct(OTHER_INCOME['增值税进项加计抵减']['2025'], OI_TOTAL['2025'])}")
    print(f"   ℹ️ 其他收益÷归母净利 {pct(OI_TOTAL['2024'], NI['2024'])} → {pct(OI_TOTAL['2025'], NI['2025'])}")
    print(f"   ℹ️ 受限资产 {RES_TOTAL['2025']/1e8:.2f}亿 = 归母净利的 {pct(RES_TOTAL['2025'], NI['2025'])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
