def flow(src_h, src_9, k, q1=None):
    """流量科目十列: Q1 / Q2派生 / H1 / Q3派生 / 前三季 × 2 年。q1 = (2025, 2026) 或 None。"""
    out = []
    for yi in (0, 1):
        a = q1[yi] if q1 else None
        h = src_h[k][yi] if k in src_h else None
        n = src_9[k][yi] if k in src_9 else None
        out += [a, (h - a) if (a is not None and h is not None) else None, h,
                (n - h) if (n is not None and h is not None) else None, n]
    return out


