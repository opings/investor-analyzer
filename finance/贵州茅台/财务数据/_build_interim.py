        # 总成本 = 8 项
        cost = (PL["营业成本"][i] + PL["利息支出_财司"][i] + PL["手续费及佣金支出"][i]
                + PL["税金及附加"][i] + PL["销售费用"][i] + PL["管理费用"][i]
                + PL["研发费用"][i] + PL["财务费用"][i])
        chk(f"{yr} 总成本拆分", cost, PL["营业总成本"][i])
        # 营业利润链
        op = (PL["营业总收入"][i] - PL["营业总成本"][i] + PL["其他收益"][i] + PL["投资收益"][i]
              + PL["公允价值变动收益"][i] + PL["信用减值损失"][i] + PL["资产处置收益"][i])
        chk(f"{yr} 营业利润链", op, PL["营业利润"][i])
        chk(f"{yr} 利润总额链", PL["营业利润"][i] + PL["营业外收入"][i] - PL["营业外支出"][i], PL["利润总额"][i])
        chk(f"{yr} 净利润链", PL["利润总额"][i] - PL["所得税费用"][i], PL["净利润"][i])
        chk(f"{yr} 归母+少数", PL["归母净利润"][i] + PL["少数股东损益"][i], PL["净利润"][i])
