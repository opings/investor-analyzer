def write_季度利润():
    path = os.path.join(OUT, "利润表-季度.csv")
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["期间", "营业收入", "归母净利润", "扣非归母净利", "经营现金流净额", "口径备注"])
