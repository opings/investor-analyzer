# ====== 勾稽自洽校验 ======
def dget(table, key, i):
    """从表中按科目名取第 i 年的值"""
    for k, vs in table:
        if k.strip() == key.strip():
            return vs[i]
    return None


def check_year(i, year):
    """对第 i 年做勾稽校验；返回 (ok, [errors])"""
    errors = []

    # --- 利润表 ---
    营收 = dget(利润表, "  营业收入", i)
    营业成本 = dget(利润表, "  营业成本", i)
    营业利润 = dget(利润表, "三、营业利润", i)
    营业外收入 = dget(利润表, "加:营业外收入", i)
    营业外支出 = dget(利润表, "减:营业外支出", i)
    利润总额 = dget(利润表, "四、利润总额", i)
    所得税 = dget(利润表, "减:所得税费用", i)
    净利润 = dget(利润表, "五、净利润", i)
    归母 = dget(利润表, "  归母净利润", i)
    少数 = dget(利润表, "  少数股东损益", i)

    # 检验 1: 营业利润 + 营业外收入 - 营业外支出 = 利润总额
    calc利润总额 = 营业利润 + 营业外收入 - 营业外支出
    if abs(calc利润总额 - 利润总额) > 100:
        errors.append(f"{year} 利润总额勾稽失败: {calc利润总额:.2f} vs {利润总额:.2f}")

    # 检验 2: 利润总额 - 所得税 = 净利润
    calc净利润 = 利润总额 - 所得税
    if abs(calc净利润 - 净利润) > 100:
        errors.append(f"{year} 净利润勾稽失败: {calc净利润:.2f} vs {净利润:.2f}")

    # 检验 3: 归母 + 少数 = 净利润
    if abs(归母 + 少数 - 净利润) > 100:
        errors.append(f"{year} 归母+少数 vs 净利润勾稽失败: {归母+少数:.2f} vs {净利润:.2f}")

    # --- 资产负债表 ---
    资产总计 = dget(资产负债表, "资产总计", i)
    负债合计 = dget(资产负债表, "负债合计", i)
    权益合计 = dget(资产负债表, "所有者权益合计", i)
    归母权益 = dget(资产负债表, "归母权益合计", i)
    少数权益 = dget(资产负债表, "少数股东权益", i)

    # 检验 4: 资产 = 负债 + 权益
    if abs(资产总计 - 负债合计 - 权益合计) > 100:
        errors.append(f"{year} 资产=负债+权益勾稽失败: {资产总计:.2f} vs {负债合计+权益合计:.2f}")

    # 检验 5: 归母权益 + 少数股东权益 = 所有者权益合计
    if abs(归母权益 + 少数权益 - 权益合计) > 100:
        errors.append(f"{year} 归母+少数股东权益 vs 合计勾稽失败")

    # --- 现金流量表 ---
    经营净额 = dget(现金流量表, "经营活动产生的现金流量净额", i)
    投资净额 = dget(现金流量表, "投资活动产生的现金流量净额", i)
    筹资净额 = dget(现金流量表, "筹资活动产生的现金流量净额", i)
    汇率变动 = dget(现金流量表, "汇率变动对现金及现金等价物的影响", i)
    净增加 = dget(现金流量表, "现金及现金等价物净增加额", i)
    期初 = dget(现金流量表, "期初现金及现金等价物余额", i)
    期末 = dget(现金流量表, "期末现金及现金等价物余额", i)

    # 检验 6: 经营+投资+筹资+汇率 = 净增加
    calc净增加 = 经营净额 + 投资净额 + 筹资净额 + (汇率变动 or 0)
    if abs(calc净增加 - 净增加) > 1000:
        errors.append(f"{year} 现金流三项+汇率 vs 净增加勾稽失败: {calc净增加:.2f} vs {净增加:.2f}")

    # 检验 7: 期初+净增加=期末
    if abs(期初 + 净增加 - 期末) > 100:
        errors.append(f"{year} 期初+净增加 vs 期末勾稽失败: {期初+净增加:.2f} vs {期末:.2f}")

    return (len(errors) == 0, errors)


def write_csv(table, filename, header_years):
    """把 [(科目名, [values...])] 写到 CSV"""
    path = os.path.join(OUT, filename)
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["科目"] + header_years)
        for k, vs in table:
            row = [k]
            for v in vs:
                if v is None:
                    row.append("")
                else:
                    row.append(v)
            w.writerow(row)
    print(f"  ✅ {filename} ({len(table)} 行 × {len(header_years)} 年)")


