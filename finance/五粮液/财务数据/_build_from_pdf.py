def build_ratios():
    """从三表派生财务比率"""
    ratios = []
    n = len(YEARS)

    def _pct(num, denom):
        return round(num / denom * 100, 2) if denom else None

    # 毛利率
    毛利率 = []
    for i in range(n):
        营收 = dget(利润表, "  营业收入", i)
        营业成本 = dget(利润表, "  营业成本", i)
        毛利率.append(_pct(营收 - 营业成本, 营收))
    ratios.append(("毛利率(%)", 毛利率))

    # 净利率
    净利率 = []
    for i in range(n):
        营收 = dget(利润表, "  营业收入", i)
        净利润 = dget(利润表, "五、净利润", i)
        净利率.append(_pct(净利润, 营收))
    ratios.append(("净利率(%)", 净利率))

    # 归母净利率
    归母净利率 = []
    for i in range(n):
        营收 = dget(利润表, "  营业收入", i)
        归母 = dget(利润表, "  归母净利润", i)
        归母净利率.append(_pct(归母, 营收))
    ratios.append(("归母净利率(%)", 归母净利率))

    # ROE (归母/期末归母权益)
    roe = []
    for i in range(n):
        归母 = dget(利润表, "  归母净利润", i)
        归母权益 = dget(资产负债表, "归母权益合计", i)
        roe.append(_pct(归母, 归母权益))
    ratios.append(("ROE(归母÷期末归母权益, %)", roe))

    # 销售费用率
    销售费用率 = []
    for i in range(n):
        营收 = dget(利润表, "  营业收入", i)
        销售费用 = dget(利润表, "  销售费用", i)
        销售费用率.append(_pct(销售费用, 营收))
    ratios.append(("销售费用率(%)", 销售费用率))

    # 管理费用率
    管理费用率 = []
    for i in range(n):
        营收 = dget(利润表, "  营业收入", i)
        管理费用 = dget(利润表, "  管理费用", i)
        管理费用率.append(_pct(管理费用, 营收))
    ratios.append(("管理费用率(%)", 管理费用率))

    # 消费税率(税金及附加/营收) - 白酒关键
    消费税率 = []
    for i in range(n):
        营收 = dget(利润表, "  营业收入", i)
        税金及附加 = dget(利润表, "  税金及附加(消费税等)", i)
        消费税率.append(_pct(税金及附加, 营收))
    ratios.append(("税金及附加/营收(%·消费税+城建教育附加)", 消费税率))

    # 经营现金流/净利 (现金含量·排雷 Step 2①)
    现金含量 = []
    for i in range(n):
        经营净额 = dget(现金流量表, "经营活动产生的现金流量净额", i)
        净利润 = dget(利润表, "五、净利润", i)
        现金含量.append(round(经营净额 / 净利润, 2))
    ratios.append(("经营现金流/净利(现金含量)", 现金含量))

    # 销售收现/营收 (含税·白酒常态 ~1.1x·2.26x=渠道压货铁证)
    收现比 = []
    for i in range(n):
        营收 = dget(利润表, "  营业收入", i)
        销售收现 = dget(现金流量表, "销售商品、提供劳务收到的现金", i)
        收现比.append(round(销售收现 / 营收, 2))
    ratios.append(("销售收现/营收(白酒常态 ~1.1x)", 收现比))

    # capex/净利 (轻/重资产)
    capex比 = []
    for i in range(n):
        capex = dget(现金流量表, "购建固定资产等支付的现金(capex)", i)
        净利润 = dget(利润表, "五、净利润", i)
        capex比.append(_pct(-capex, 净利润))
    ratios.append(("capex/净利(%·轻/重资产)", capex比))

    # 应收周转天数
    应收周转 = []
    for i in range(n):
        营收 = dget(利润表, "  营业收入", i)
        应收账款 = dget(资产负债表, "应收账款", i) or 0
        应收周转.append(round(应收账款 / 营收 * 365, 1))
    ratios.append(("应收账款周转天数", 应收周转))

    # 存货周转天数
    存货周转 = []
    for i in range(n):
        营业成本 = dget(利润表, "  营业成本", i)
        存货 = dget(资产负债表, "存货", i)
        存货周转.append(round(存货 / 营业成本 * 365, 1))
    ratios.append(("存货周转天数", 存货周转))

    # 合同负债+预收款项 / 营收 (蓄水池,考虑 2020 前后科目切换)
    合负债比 = []
    for i in range(n):
        营收 = dget(利润表, "  营业收入", i)
        合同负债 = dget(资产负债表, "合同负债", i) or 0
        预收款项 = dget(资产负债表, "预收款项", i) or 0
        蓄水池 = 合同负债 + 预收款项
        合负债比.append(_pct(蓄水池, 营收))
    ratios.append(("(合同负债+预收)/营收(%·预收蓄水池)", 合负债比))

    # 资产负债率
    资产负债率 = []
    for i in range(n):
        资产 = dget(资产负债表, "资产总计", i)
        负债 = dget(资产负债表, "负债合计", i)
        资产负债率.append(_pct(负债, 资产))
    ratios.append(("资产负债率(%)", 资产负债率))

    # 分红/归母 (估算·按当年发生的分红派息现金)
    分红率 = []
    for i in range(n):
        分红 = dget(现金流量表, "分配股利、利润或偿付利息支付的现金", i)
        归母 = dget(利润表, "  归母净利润", i)
        分红率.append(_pct(-分红, 归母) if 分红 is not None else None)
    ratios.append(("当年现金分红/归母(%·含少数股东部分)", 分红率))

    return ratios


