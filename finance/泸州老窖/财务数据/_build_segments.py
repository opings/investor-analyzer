# -*- coding: utf-8 -*-
"""分部营收(2020-2025 新口径·营业收入·元)→ 分部营收.csv。
口径:2020 起年报用「中高档酒类/其他酒类」二分 + 境内外 + 传统/新兴渠道,连续可比。
2006-2019 为「高档/中档/低档」旧口径(多次调整·不可直接拼接),高端化趋势见财务比率.csv 毛利率序列。
数据源:_extract_json/lzlj_extract_{2021,2023,2025}.json 的分部营收字段(重述口径:偶数年取次年年报上年列)。"""
import csv
import json
import os

OUT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(OUT, "_extract_json")


def load(y):
    with open(os.path.join(SRC, f"lzlj_extract_{y}.json"), encoding="utf-8") as f:
        return json.load(f)["分部营收"]


def num(v):
    if v is None:
        return None
    if isinstance(v, (int, float)):
        return float(v)
    try:
        return float(str(v).replace(",", ""))
    except (ValueError, TypeError):
        return None


# 2021.json: 按产品/按地区/按销售模式 -> 本年(2021)/上年(2020) -> 科目 -> 营业收入
s21 = load(2021)
# 2023.json: 按产品 -> 科目 -> 本年(2023)/上年(2022)
s23 = load(2023)
# 2025.json: "按产品-中高档酒类": [本年2025, 上年2024]
s25 = load(2025)

# 组装每年值:{行名: {年: 值}}
data = {}


def put(row, year, val):
    data.setdefault(row, {})[year] = num(val)


# --- 2020, 2021 (from 2021.json) ---
p21 = s21["按产品"]
put("中高档酒类营业收入", 2021, p21["本年"]["中高档酒类"]["营业收入"])
put("中高档酒类营业收入", 2020, p21["上年"]["中高档酒类"]["营业收入"])
put("其他酒类营业收入", 2021, p21["本年"]["其他酒类"]["营业收入"])
put("其他酒类营业收入", 2020, p21["上年"]["其他酒类"]["营业收入"])
put("其他收入(非酒)", 2021, p21["本年"]["其他收入(其他业务)"]["营业收入"])
put("其他收入(非酒)", 2020, p21["上年"]["其他收入(其他业务)"]["营业收入"])
g21 = s21["按地区"]
put("境内", 2021, g21["本年"]["国内"]["营业收入"])
put("境内", 2020, g21["上年"]["国内"]["营业收入"])
put("境外", 2021, g21["本年"]["国外"]["营业收入"])
put("境外", 2020, g21["上年"]["国外"]["营业收入"])
m21 = s21["按销售模式"]
put("传统渠道", 2021, m21["本年"]["传统渠道运营模式"]["营业收入"])
put("传统渠道", 2020, m21["上年"]["传统渠道运营模式"]["营业收入"])
put("新兴渠道", 2021, m21["本年"]["新兴渠道运营模式"]["营业收入"])
put("新兴渠道", 2020, m21["上年"]["新兴渠道运营模式"]["营业收入"])

# --- 2022, 2023 (from 2023.json) ---
p23 = s23["按产品"]
put("中高档酒类营业收入", 2023, p23["中高档酒类"]["本年"])
put("中高档酒类营业收入", 2022, p23["中高档酒类"]["上年"])
put("其他酒类营业收入", 2023, p23["其他酒类"]["本年"])
put("其他酒类营业收入", 2022, p23["其他酒类"]["上年"])
put("其他收入(非酒)", 2023, p23["其他收入"]["本年"])
put("其他收入(非酒)", 2022, p23["其他收入"]["上年"])
g23 = s23["按地区"]
put("境内", 2023, g23["境内"]["本年"])
put("境内", 2022, g23["境内"]["上年"])
put("境外", 2023, g23["境外"]["本年"])
put("境外", 2022, g23["境外"]["上年"])
m23 = s23["按销售模式"]
put("传统渠道", 2023, m23["传统渠道运营模式"]["本年"])
put("传统渠道", 2022, m23["传统渠道运营模式"]["上年"])
put("新兴渠道", 2023, m23["新兴渠道运营模式"]["本年"])
put("新兴渠道", 2022, m23["新兴渠道运营模式"]["上年"])

# --- 2024, 2025 (from 2025.json: [本年2025, 上年2024]) ---
put("中高档酒类营业收入", 2025, s25["按产品-中高档酒类"][0])
put("中高档酒类营业收入", 2024, s25["按产品-中高档酒类"][1])
put("其他酒类营业收入", 2025, s25["按产品-其他酒类"][0])
put("其他酒类营业收入", 2024, s25["按产品-其他酒类"][1])
put("其他收入(非酒)", 2025, s25["按产品-其他收入(非酒)"][0])
put("其他收入(非酒)", 2024, s25["按产品-其他收入(非酒)"][1])
put("境内", 2025, s25["按地区-境内"][0])
put("境内", 2024, s25["按地区-境内"][1])
put("境外", 2025, s25["按地区-境外"][0])
put("境外", 2024, s25["按地区-境外"][1])
put("传统渠道", 2025, s25["按销售模式-传统渠道运营模式"][0])
put("传统渠道", 2024, s25["按销售模式-传统渠道运营模式"][1])
put("新兴渠道", 2025, s25["按销售模式-新兴渠道运营模式"][0])
put("新兴渠道", 2024, s25["按销售模式-新兴渠道运营模式"][1])

YEARS = list(range(2020, 2026))
ROWS = ["中高档酒类营业收入", "其他酒类营业收入", "其他收入(非酒)",
        "境内", "境外", "传统渠道", "新兴渠道"]

# 派生:中高档占酒类比、中高档营收同比
def add_derived():
    zhonggao = data["中高档酒类营业收入"]
    other = data["其他酒类营业收入"]
    ratio = {}
    yoy = {}
    for y in YEARS:
        zg, ot = zhonggao.get(y), other.get(y)
        if zg is not None and ot is not None and (zg + ot):
            ratio[y] = round(zg / (zg + ot) * 100, 2)
        if zg is not None and zhonggao.get(y - 1):
            yoy[y] = round((zg / zhonggao[y - 1] - 1) * 100, 2)
    data["中高档占酒类比(%)"] = ratio
    data["中高档营收同比(%)"] = yoy


add_derived()
ROWS += ["中高档占酒类比(%)", "中高档营收同比(%)"]

path = os.path.join(OUT, "分部营收.csv")
with open(path, "w", encoding="utf-8-sig", newline="") as f:
    w = csv.writer(f)
    w.writerow(["科目(单位:元;比率行为%)"] + [str(y) for y in YEARS])
    for r in ROWS:
        w.writerow([r] + ["" if data.get(r, {}).get(y) is None else data[r][y] for y in YEARS])
print(f"✅ 分部营收.csv ({len(ROWS)} 行 × {len(YEARS)} 年 · 2020-2025 新口径)")
# 校验:中高档+其他酒+非酒 ≈ 营业收入(核对2025)
chk = (data["中高档酒类营业收入"][2025] + data["其他酒类营业收入"][2025] + data["其他收入(非酒)"][2025])
print(f"   2025 三档合计 = {chk/1e8:.2f}亿(应≈营业收入 257.31亿)")
print(f"   2025 中高档占酒类比 = {data['中高档占酒类比(%)'][2025]}%(事实编年:89.26%)")
