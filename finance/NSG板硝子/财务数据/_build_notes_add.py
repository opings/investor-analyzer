#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""NSG 附注增补构建器 → 附注增补.csv

背景（2026-09-14 全库附注审计）：NSG 库经复查**不存在系统性漏读**——
Apollo 资本重构（¥450 认购 / 257.64% / 72.07% / ¥500 挤出 / 拟似DES ¥1,400 亿 / 退市 / 继续企业前提）
在 `分析.md` 与编年里记得比审计抽出来的还全。审计报的 5 条中：
  · 「日后事项零痕迹」= **检测器误报**（库里用「后发事项」，我的关键词只写了「期后/日后」）
  · 政府补助、在建工程 = **提出会社（母公司単体）**口径的小项，不入连结库合理
  · 真正缺的只有本表这三样。
故本表是**增补**，不是修复。

数据来源（全部一手·FY2026/3 有価証券報告書 第160期）：
  · 注 41 コミットメント（設備投資契約）
  · 注 42 関連当事者との取引（製品及びサービス等の販売）
  · 第一部 企業の概況 1【主要な経営指標等の推移】(2) 提出会社 —— 発行済株式総数（分类别）
  · 第4 提出会社の状況 1【株式等の状況】(1)【株式の総数等】—— 発行可能株式総数 / 発行済株式 / A 种转换注记
"""
import csv, os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "附注增补.csv")

# 已签约未发生的资本支出（連結·百万円）
CAPEX_COMMIT = {"FY2025/3": 2233, "FY2026/3": 7385}

# 关联方销售（連結·百万円）
RPT_SALES = {
    "製品等の販売-ジョイント・ベンチャー": {"FY2025/3": 481, "FY2026/3": 849},
    "製品等の販売-関連会社": {"FY2025/3": 2201, "FY2026/3": 3221},
    "サービスの販売-ジョイント・ベンチャー": {"FY2025/3": 2, "FY2026/3": None},
    "サービスの販売-関連会社": {"FY2025/3": 1, "FY2026/3": 1},
}
RPT_TOTAL = {"FY2025/3": 2685, "FY2026/3": 4071}

# 発行済株式総数（提出会社·千株）
SHARES = {
    "普通株式": {"第156期 FY2022/3": 91000, "第157期 FY2023/3": 91167, "第158期 FY2024/3": 91401,
                "第159期 FY2025/3": 91539, "第160期 FY2026/3": 142319},
    "A種種類株式": {"第156期 FY2022/3": 30, "第157期 FY2023/3": 30, "第158期 FY2024/3": 30,
                   "第159期 FY2025/3": 30, "第160期 FY2026/3": 23},
}
PERIODS = ["第156期 FY2022/3", "第157期 FY2023/3", "第158期 FY2024/3",
           "第159期 FY2025/3", "第160期 FY2026/3"]


def main():
    errs, nchk = [], 0

    # 校验①：关联方分项之和 = 合計
    for y in ("FY2025/3", "FY2026/3"):
        nchk += 1
        s = sum(v[y] for v in RPT_SALES.values() if v[y] is not None)
        if s != RPT_TOTAL[y]:
            errs.append(f"[{y}] 关联方分项之和 {s} ≠ 合計 {RPT_TOTAL[y]}")
    # 校验②：资本支出承诺为正
    for y, v in CAPEX_COMMIT.items():
        nchk += 1
        if v <= 0:
            errs.append(f"[{y}] 設備投資契約 非正")
    # 校验③：普通股数单调（除非发生减资/合并）
    nchk += 1
    seq = [SHARES["普通株式"][p] for p in PERIODS]
    if any(b < a for a, b in zip(seq, seq[1:])):
        errs.append("普通株式数出现下降，需核对是否发生股份合并/减资")

    if errs:
        print(f"❌ 校验不通过 {len(errs)}：")
        for e in errs:
            print("   ✗", e)
        return 1

    jump = SHARES["普通株式"]["第160期 FY2026/3"] / SHARES["普通株式"]["第159期 FY2025/3"] * 100 - 100

    rows = [
        ["单位:百万円(JPY millions) / 千株。空=该期未列示"],
        ["来源:FY2026/3 有価証券報告書 第160期 —— 注41 コミットメント / 注42 関連当事者との取引 / 主要な経営指標等の推移(2)提出会社"],
        ["🔵 本表性质=**增补**非修复。2026-09-14 全库附注审计复查确认:NSG 库无系统性漏读,"
         "Apollo 资本重构已在 `分析.md` 与编年中完整记录(¥450 认购/257.64%/72.07%/¥500 挤出/拟似DES ¥1,400亿/退市)"],
        [],
        ["【A · 設備投資契約（已签约但尚未发生的资本支出·連結）】🔑 指向未来的硬数字"],
        ["项目", "FY2025/3末", "FY2026/3末", "变动"],
        ["有形固定資産", CAPEX_COMMIT["FY2025/3"], CAPEX_COMMIT["FY2026/3"],
         f"{CAPEX_COMMIT['FY2026/3'] / CAPEX_COMMIT['FY2025/3'] * 100 - 100:+.0f}%"],
        ["🔑 读法:一家正被债务锁死、即将被 Apollo 重组退市的公司，**已签约资本支出承诺一年翻了三倍**。"
         "须与「事业等风险」自陈的「逾 ¥1,000 亿到期借款」并看——扩张承诺与偿债压力同时在升"],
        [],
        ["【B · 関連当事者との取引（销售·連結）】"],
        ["项目", "FY2025/3", "FY2026/3", "变动"],
    ]
    for k, v in RPT_SALES.items():
        a, b = v["FY2025/3"], v["FY2026/3"]
        chg = "" if (a in (None, 0) or b is None) else f"{b / a * 100 - 100:+.0f}%"
        rows.append([k, a if a is not None else "", b if b is not None else "", chg])
    rows.append(["合計", RPT_TOTAL["FY2025/3"], RPT_TOTAL["FY2026/3"],
                 f"{RPT_TOTAL['FY2026/3'] / RPT_TOTAL['FY2025/3'] * 100 - 100:+.1f}%"])
    rows.append(["⚠️ 有報自陈「独立第三者間取引に適用される通常の取引条件に基づき行われています」"
                 "（译:按适用于独立第三方交易的通常条件进行）。关联方=合营企业与联营企业，非控股股东"])

    rows += [
        [],
        ["【C · 発行済株式総数（提出会社·千株）】🔴 FY2026/3 普通股数异动"],
        ["股份种类"] + PERIODS,
    ]
    for k in ("普通株式", "A種種類株式"):
        rows.append([k] + [SHARES[k][p] for p in PERIODS])
    rows += [
        [f"🔴 普通株式 FY2025/3 → FY2026/3 由 {SHARES['普通株式']['第159期 FY2025/3']:,} 千股增至 "
         f"{SHARES['普通株式']['第160期 FY2026/3']:,} 千股（{jump:+.1f}%），"
         f"而 A種種類株式账面仅由 30 千股减至 23 千股——**注意：A 种股数的减少量不等于换出的普通股数**（见下行）"],
        ["✅ 来源已查实（有報「株式の総数等」②発行済株式 注3）：**2026年3月24日，A種種類株主行使「以普通股为对价的"
         "取得请求权」，公司交付普通株 38,252,710 股作为对价**（该批 A 种股为未消却株式）。"
         "这解释了 +50,780 千股中的 38,253 千股；余下约 12,527 千股来自新株予約権行使等，有報未单列 ⏳"],
        ["🔴 **时点即信号**：A 种转换发生在 **2026-03-24 —— 与 Apollo 股份引受契约签订同一天**。"
         "即优先股转普通股是资本重构的**排序动作**，在 Apollo 配售之前先行稀释普通股约四成【推】"],
        ["🔴 **一条容易漏的前置依赖**：期末発行可能株式総数（定款上限）仅 **177,500,000 股**，"
         "而 Apollo 第三者配发为 **366,666,666 股** —— **远超现行定款上限**，"
         "故交易必然以**定款变更（提高发行可能株式总数）**为前提。该前提是否通过股东大会，是交易能否落地的硬节点"],
        ["ℹ️ 期末数（2026-03-31）：普通株式 142,319,262 股 + A種種類株式 22,644 股 = 142,341,906 股；"
         "提出日（2026-06-25）普通株式 142,340,462 股。A 种为**非上场**，单元株式数 1 股"],
        ["ℹ️ 潜在稀释:有報自陈 ストック・オプション / 譲渡制限付株式報酬 / A種種類株式の転換 "
         "因当期为亏损而**不具稀释效果（反稀释）**，故未计入稀释每股。**亏损年份的「无稀释」不等于无潜在稀释**"],
    ]

    with open(OUT, "w", encoding="utf-8", newline="") as f:
        csv.writer(f).writerows(rows)

    print(f"── 附注增补校验：{nchk} 条，不通过 0")
    print("✅ 附注增补.csv 已写出（設備投資契約 / 関連当事者 / 発行済株式総数）")
    print(f"   🔑 設備投資契約 {CAPEX_COMMIT['FY2025/3']:,} → {CAPEX_COMMIT['FY2026/3']:,} 百万円（+231%）")
    print(f"   🔑 关联方销售 {RPT_TOTAL['FY2025/3']:,} → {RPT_TOTAL['FY2026/3']:,} 百万円（+51.6%）")
    print(f"   🔴 普通株式 91,539 → 142,319 千股（{jump:+.1f}%）——A 种优先股 2026-03-24 转换交付 38,253 千股为主因")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
