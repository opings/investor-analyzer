def check():
    errors = []
    stats = {"executed": 0}

    def eq(label, a, b):
        stats["executed"] += 1
        if a != b:
            errors.append(f"{label}: {a} vs {b} (差 {a - b:+})")

    def v(block, key, i):
        return dict(BLOCKS[block])[key][i]

    revenue, total_expense = h1_revenue()
    for i, p in enumerate(P):
        eq(f"[{p}] 四区域加总 = 总计", sum(v("区域", k, i) for k, _ in 区域[:4]), v("区域", "总计 Total", i))
        eq(f"[{p}] 区域总计 = H1 利润表营收", v("区域", "总计 Total", i), revenue[i])
        for block, region in (("中国渠道", "中国 PRC(含港澳台)"), ("亚太渠道", "亚太 Asia Pacific"),
                              ("美洲渠道", "美洲 Americas"), ("欧洲渠道", "欧洲及其他 Europe and others")):
            rows = BLOCKS[block]
            keys = [k for k, _ in rows]
            off_i, on_i, ws_i = keys.index("线下渠道"), keys.index("线上渠道"), keys.index("批发及其他")
            eq(f"[{p}] {block} 线下 = 明细加总", sum(rows[j][1][i] for j in range(off_i + 1, on_i)), rows[off_i][1][i])
            eq(f"[{p}] {block} 线上 = 明细加总", sum(rows[j][1][i] for j in range(on_i + 1, ws_i)), rows[on_i][1][i])
            eq(f"[{p}] {block} 线下 + 线上 + 批发 = 合计",
               rows[off_i][1][i] + rows[on_i][1][i] + rows[ws_i][1][i], v(block, "合计", i))
            eq(f"[{p}] {block} 合计 = 区域表", v(block, "合计", i), v("区域", region, i))
        artists = [k for k, _ in 按IP if k.startswith("  ")]
        eq(f"[{p}] 艺术家IP 明细加总 = 小计", sum(v("按IP", k, i) for k in artists), v("按IP", "艺术家IP小计", i))
        eq(f"[{p}] 艺术家 + 授权 = 自主产品", v("按IP", "艺术家IP小计", i) + v("按IP", "授权IP", i), v("按IP", "自主产品合计", i))
        eq(f"[{p}] 自主 + 外采 = 总计", v("按IP", "自主产品合计", i) + v("按IP", "外采及其他", i), v("按IP", "总计", i))
        eq(f"[{p}] IP 总计 = H1 营收", v("按IP", "总计", i), revenue[i])
        eq(f"[{p}] 品类加总 = 总计", sum(v("按品类", k, i) for k, _ in 按品类[:3]), v("按品类", "总计", i))
        eq(f"[{p}] 品类总计 = H1 营收", v("按品类", "总计", i), revenue[i])
        exp = dict(费用按性质)
        eq(f"[{p}] 费用按性质加总 = 总计", sum(vals[i] for k, vals in 费用按性质[:-1]), exp["总计"][i])
        eq(f"[{p}] 费用总计 = 销售成本 + 经销 + 行政", exp["总计"][i], total_expense[i])

    # 比较列 vs 2025 中报当年列
    for block, mapping in 当年列_2025H1.items():
        for k, val in mapping.items():
            eq(f"[2025H1 当年列] {block} {k}", v(block, k, 0), val)
    for label, block, keys, orig in 重分类组:
        eq(f"[2025H1 重分类] {label}", sum(v(block, k, 0) for k in keys), sum(orig))

    # 门店: 区域加总 = 全球; 期末 − 期初 = 净增
    stores = dict(门店与会员)
    for t in (1, 2):
        eq(f"[{门店时点[t]}] 四区域零售店 = 全球", sum(stores[k][t] for k in ("零售店·中国", "零售店·亚太", "零售店·美洲",
                                                                   "零售店·欧洲及其他")), stores["零售店·全球合计"][t])
    for k, inc in 门店净增_2026H1.items():
        eq(f"[2026H1 净增] {k}", stores[k][2] - stores[k][1], inc)
    eq("[2026-06-30 vs 2025-06-30] 全球零售店净增 105(2026 中报自述)", stores["零售店·全球合计"][2] - stores["零售店·全球合计"][0], 105)

    # 季度更新: 区间下限 ≤ 上限; 同一期间维度不重复
    seen = set()
    for period, dim, lo, hi in 季度更新:
        stats["executed"] += 1
        if lo > hi:
            errors.append(f"[{period}] {dim} 区间下限 {lo} > 上限 {hi}")
        stats["executed"] += 1
        if (period, dim) in seen:
            errors.append(f"[{period}] {dim} 重复")
        seen.add((period, dim))
    return errors, stats


def mutation_test(show_list=False):
    targets = []
    for name, rows in list(BLOCKS.items()) + [("费用按性质", 费用按性质), ("门店与会员", 门店与会员)]:
        for k, vals in rows:
            for i, x in enumerate(vals):
                if x is not None:
                    targets.append((name, k, i, vals))
    caught, missed = 0, []
    for name, k, i, vals in targets:
        original = vals[i]
        vals[i] = original + 1
        errors, _ = check()
        vals[i] = original
        if errors:
            caught += 1
        else:
            missed.append(f"{name} · {k.strip()} · 列{i}")
    print(f"变异对照: 共 {len(targets)} 个数值格逐格 +1, 被勾稽捕获 {caught} 个 ({caught / len(targets):.1%}), 未覆盖 {len(missed)} 个")
    if show_list:
        for m in missed:
            print(f"  未覆盖: {m}")


