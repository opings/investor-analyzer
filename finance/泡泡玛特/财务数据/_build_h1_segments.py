def h1_revenue():
    """取 H1 构建脚本内存表里的营收(不读 CSV)。"""
    spec = importlib.util.spec_from_file_location("popmart_h1_build", os.path.join(OUT, "_build_h1_from_pdf.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    rev = dict(mod.利润表_H1)["收益 Revenue"]
    cost = dict(mod.利润表_H1)["销售成本 Cost of sales"]
    ds = dict(mod.利润表_H1)["经销及销售开支 Distribution and selling expenses"]
    ga = dict(mod.利润表_H1)["一般及行政开支 G&A expenses"]
    idx = [mod.H1_PERIODS.index(p) for p in P]
    return ([rev[i] for i in idx], [-(cost[i] + ds[i] + ga[i]) for i in idx])


