def write_csv(fname, data):
    path = os.path.join(OUT, fname)
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(data["headers"])
        for row in data["rows"]:
            w.writerow(row)
    print(f"  ✅ {fname}: {len(data['rows'])} rows × {len(data['headers'])} cols")

