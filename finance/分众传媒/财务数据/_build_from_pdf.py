NO_SCALE_KEYS = ("每股收益", "ROE")  # 不做单位换算


def tol(y):
    return 600.0 if y in WAN_YEARS else 1.0  # 万元源容忍 0.06 万(四舍五入累积)


DATA = {}
for y in YEARS:
    with open(os.path.join(SRC, f"fm_{y}.json"), encoding="utf-8") as f:
        raw = json.load(f)
    scale = 10000.0 if y in WAN_YEARS else 1.0
    d = {"meta": raw["meta"], "每股收益(元/股)": raw.get("每股收益(元/股)")}
    for tbl in ("利润表", "资产负债表", "现金流量表", "补充"):
        d[tbl] = {}
        for k, v in raw.get(tbl, {}).items():
            if v is None:
                continue
            if any(nk in k for nk in NO_SCALE_KEYS):
                d[tbl][k] = float(v)
            else:
                d[tbl][k] = float(v) * scale
    DATA[y] = d

ERR = []


def ck(y, label, lhs, rhs, t=None):
    t = t if t is not None else tol(y)
    if lhs is None or rhs is None:
        return
    if abs(lhs - rhs) > t:
        ERR.append(f"[{y}] {label}: {lhs:,.2f} vs {rhs:,.2f} (差 {lhs-rhs:,.2f})")


def g(y, tbl, key):
    return DATA[y][tbl].get(key)


def s(y, tbl, keys):
    vals = [g(y, tbl, k) for k in keys]
    present = [v for v in vals if v is not None]
    return sum(present) if present else None


