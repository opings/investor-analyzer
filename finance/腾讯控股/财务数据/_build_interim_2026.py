TOL = 2  # 百万元容差(报表内部四舍五入)


def close(a: float, b: float, tol: float = TOL) -> bool:
    return abs(a - b) <= tol


def check(label: str, a: float, b: float, tol: float = TOL) -> None:
    if not close(a, b, tol):
        raise AssertionError(f"勾稽不平: {label}: {a} vs {b} (差 {a-b})")


def col(d: dict, name: str) -> tuple:
    return d[name]


